export function getDevotionalForDate(dateStr: string): DevotionalPublic {
  // First check exact match in approved vault
  const found = APPROVED_DEVOTIONALS_VAULT.find(d => d.date === dateStr);
  if (found) {
    return found;
  }

  // If not found, use deterministic modulo mapping so any future date has a rich, high-score devotional
  const hash = dateStr.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  const fallbackIndex = hash % APPROVED_DEVOTIONALS_VAULT.length;
  const template = APPROVED_DEVOTIONALS_VAULT[fallbackIndex];

  return {
    ...template,
    id: dateStr,
    date: dateStr
  };
}

export function getAllPublishedDevotionals(): DevotionalPublic[] {
  return APPROVED_DEVOTIONALS_VAULT;
}
